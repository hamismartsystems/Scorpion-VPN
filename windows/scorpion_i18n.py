def set_lang(lang):
    global LANG
    LANG = "fa" if lang == "fa" else "en"


def tr(key, *args):
    d = _FA if LANG == "fa" else _EN
    s = d.get(key)
    if s is None:
        s = _EN.get(key, key)
    if args:
        try:
            return s % args
        except (TypeError, ValueError):
            return s
    return s
